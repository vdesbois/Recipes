export function getLocale() {
  return localStorage.getItem(localeStorageKey) === "fr" ? "fr" : "en";
}

export function t(key, values = {}) {
  const locale = getLocale();
  const template = translations[locale][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ""));
}

export function translateError(message) {
  const key = apiErrorKeys.get(message);
  return key ? t(key) : message;
}

function updateLocaleControls(locale) {
  for (const dropdown of document.querySelectorAll(".locale-dropdown")) {
    const option = dropdown.querySelector(`[data-locale="${locale}"]`);
    const flag = dropdown.querySelector("[data-current-locale-flag]");
    const label = dropdown.querySelector("[data-current-locale-label]");
    const trigger = dropdown.querySelector(".locale-trigger");
    flag.replaceChildren(option.querySelector("svg").cloneNode(true));
    label.textContent = locale.toUpperCase();
    trigger.setAttribute(
      "aria-label",
      t("locale.switch", {
        language: t(locale === "en" ? "locale.english" : "locale.french"),
      }),
    );
    for (const button of dropdown.querySelectorAll("[data-locale]")) {
      button.setAttribute("aria-current", String(button.dataset.locale === locale));
    }
  }
}

export function applyTranslations() {
  const locale = getLocale();
  document.documentElement.lang = locale === "fr" ? "fr-CA" : "en-CA";
  document.title = t(document.body.dataset.titleKey ?? "app.title");
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  }
  for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  }
  updateLocaleControls(locale);
}

export function initializeLocalization() {
  applyTranslations();
  document.querySelectorAll("[data-locale]").forEach((button) => {
    button.addEventListener("click", () => {
      localStorage.setItem(localeStorageKey, button.dataset.locale);
      applyTranslations();
      button.closest(".locale-dropdown").open = false;
      document.dispatchEvent(new Event("localechange"));
    });
  });
}
